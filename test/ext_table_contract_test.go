package main

// Contract test for the external-tool items (--ext-op).
//
// The addendum (simulation-addendum.md, items 451-530) is the spec: it names
// every item, its route, whether it wants a target and the class it must
// answer with. This test walks the addendum, checks the registry against it,
// runs every item through the built binary and records what the machine
// answered.
//
// Regenerate the observed classes with:
//
//	go test -run ExtTableContract -update-ext
//
// The addendum's contract class is the nominal one (what the item must
// answer when the tool is absent); observed is what this machine answered
// (the tool present or absent, a device attached or not). A difference
// between the two is normal and is not a defect; a difference outside the
// accepted set is.

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"flag"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
	"testing"
	"time"
)

var updateExtTable = flag.Bool("update-ext", false, "rewrite testdata/ext_ops.json from this run's observations")

const (
	extTablePath = "testdata/ext_ops.json"
	extTableNote = "External-tool contract table: one row per addendum item (451-530). Generated by `go test -run ExtTableContract -update-ext`; do not hand-edit. expect is the addendum's contract, observed is the class this machine answered."
	// extAddendumPath is the spec, read from the repository root.
	extAddendumPath = "../env/archive/spec/simulation-addendum.md"
	// ghidraRowTimeout is the floor for a route G row that really imports: a
	// cold Mach-O measured 73 s alone and crossed 110 s under `go test ./...`
	// load, and the row needs both the CLI budget and the harness kill above it.
	ghidraRowTimeout = 180 * time.Second
)

type extTable struct {
	Note string        `json:"note"`
	Ops  []extTableRow `json:"ops"`
}

type extTableRow struct {
	Name     string      `json:"name"`
	Item     int         `json:"item"`
	Route    string      `json:"route"`
	Needs    bool        `json:"needs"`
	Expect   extExpect   `json:"expect"`
	Observed extObserved `json:"observed"`
}

type extExpect struct {
	NoArgs     string `json:"no_args"`
	WithTarget string `json:"with_target"`
	Fixture    string `json:"fixture,omitempty"`
}

type extObserved struct {
	NoArgs     string `json:"no_args"`
	WithTarget string `json:"with_target,omitempty"`
}

// extAccepted is the live class set each contract class accepts. The
// addendum names the contract; the machine decides which accepted class it
// lands on. A class outside the set is a defect, not a drift.
var extAccepted = map[string][]string{
	// no_engine: the tool is absent (no_engine) or present (ok). timeout
	// stays excluded: the contract run has its own budget, a hang is a defect.
	opClassNoEngine:      {opClassNoEngine, opClassOK},
	opClassNeedsArg:      {opClassNeedsArg},
	opClassNotApplicable: {opClassNotApplicable},
	opClassSkippedTool:   {opClassNoEngine, opClassOK, opClassNeedsArg},
	opClassSkippedGhidra: {opClassNoEngine, opClassOK, opClassNeedsArg},
}

func extClassAccepted(nominal, live string) bool {
	return slices.Contains(extAccepted[nominal], live)
}

// addItemRe reads one addendum item: its number and the op name it names.
var addItemRe = regexp.MustCompile("^- \\[ \\] \\*\\*(\\d+)\\.\\*\\* `([a-z0-9_]+)`")

// addContractRe reads the addendum's contract sentence: route, whether the
// item wants a target, and the class it must answer with without and with a
// target.
var addContractRe = regexp.MustCompile("Route ([YG]), (no target required|target required)\\. Contract: without target `([a-z_]+)`, with target `([a-z_]+)`, on fixture `([a-z_-]+)`")

// extAddendumItem is one row of the addendum, parsed.
type extAddendumItem struct {
	Number     int
	Name       string
	Route      string
	Needs      bool
	NoArgs     string
	WithTarget string
	Fixture    string
}

// readExtAddendum parses the addendum into its items. The addendum is the
// spec: a row that does not parse is a spec change, not a test bug.
func readExtAddendum(t *testing.T) []extAddendumItem {
	t.Helper()
	b := readSpec(t, extAddendumPath)
	var items []extAddendumItem
	for line := range strings.SplitSeq(string(b), "\n") {
		m := addItemRe.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		c := addContractRe.FindStringSubmatch(line)
		if c == nil {
			t.Fatalf("addendum item %s has no contract sentence: %s", m[1], line)
		}
		n := 0
		for _, d := range m[1] {
			n = n*10 + int(d-'0')
		}
		items = append(items, extAddendumItem{
			Number:     n,
			Name:       m[2],
			Route:      c[1],
			Needs:      c[2] == "target required",
			NoArgs:     c[3],
			WithTarget: c[4],
			Fixture:    c[5],
		})
	}
	return items
}

// TestExtAddendumIsWhole walks the addendum and proves it still holds 80
// items numbered 451 to 530 with no gap: a missing item is a spec change
// that the inventory below would not see.
func TestExtAddendumIsWhole(t *testing.T) {
	items := readExtAddendum(t)
	if len(items) != 80 {
		t.Fatalf("addendum holds %d items, want 80 (451-530)", len(items))
	}
	for i, it := range items {
		want := 451 + i
		if it.Number != want {
			t.Fatalf("addendum item %d is out of order at position %d", it.Number, i)
		}
	}
}

// TestExtTableContractInventory is the drift check: the addendum, the
// registry and the published table must name the same items with the same
// route and the same needs flag. A new item without a row, or a row for an
// item that no longer exists, fails here before any process is started.
func TestExtTableContractInventory(t *testing.T) {
	items := readExtAddendum(t)
	tbl, err := loadExtTable(extTablePath)
	if err != nil {
		t.Fatalf("load %s: %v\ngenerate it with: go test -run ExtTableContract -update-ext", extTablePath, err)
	}
	rows := map[string]extTableRow{}
	for _, row := range tbl.Ops {
		if _, dup := rows[row.Name]; dup {
			t.Errorf("%s lists %q twice", extTablePath, row.Name)
		}
		rows[row.Name] = row
	}
	seen := map[string]bool{}
	for _, it := range items {
		o, ok := extOps[it.Name]
		if !ok {
			t.Errorf("addendum item %d names %q, which is not a registered ext op", it.Number, it.Name)
			continue
		}
		seen[it.Name] = true
		if o.route != it.Route {
			t.Errorf("%s: addendum says route %s, registered as %s", it.Name, it.Route, o.route)
		}
		if o.needs != it.Needs {
			t.Errorf("%s: addendum says needs=%v, registered as needs=%v", it.Name, it.Needs, o.needs)
		}
		row, ok := rows[it.Name]
		if !ok {
			t.Errorf("%s has no row in %s (rerun with -update-ext)", it.Name, extTablePath)
			continue
		}
		if row.Item != it.Number {
			t.Errorf("%s: table says item %d, addendum says %d", it.Name, row.Item, it.Number)
		}
		if row.Route != it.Route || row.Needs != it.Needs {
			t.Errorf("%s: table route/needs %s/%v, addendum %s/%v", it.Name, row.Route, row.Needs, it.Route, it.Needs)
		}
		if row.Expect.NoArgs != it.NoArgs || row.Expect.WithTarget != it.WithTarget {
			t.Errorf("%s: table expect %s/%s, addendum %s/%s", it.Name, row.Expect.NoArgs, row.Expect.WithTarget, it.NoArgs, it.WithTarget)
		}
	}
	for _, name := range extOpNames() {
		if !seen[name] {
			t.Errorf("registered ext op %q has no addendum item", name)
		}
	}
	for _, row := range tbl.Ops {
		if _, ok := extOps[row.Name]; !ok {
			t.Errorf("%s row %q is not a registered ext op (stale table; rerun with -update-ext)", extTablePath, row.Name)
		}
	}
	t.Logf("%d addendum items, %d registered ext ops, %d table rows", len(items), len(extOps), len(tbl.Ops))
}

// extRunSpec is one contract run of the built CLI.
type extRunSpec struct {
	Binary  string
	Name    string
	Target  string
	Args    []string
	Dir     string
	Env     []string
	Timeout time.Duration
}

// runExtContract executes `lrecon --ext-op NAME [TARGET] [ARG...]` and
// reports its exit code. A timeout is reported as the timeout class, not as
// an error, so the test can name the item and its budget instead of dying
// on exec.
func runExtContract(spec extRunSpec) (rc int, stdout, stderr, class string) {
	args := []string{"--ext-op", spec.Name}
	if spec.Target != "" {
		args = append(args, spec.Target)
	}
	args = append(args, spec.Args...)
	ctx, cancel := context.WithTimeout(context.Background(), spec.Timeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, spec.Binary, args...)
	cmd.Dir = spec.Dir
	cmd.Env = spec.Env
	var out, errb bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errb
	err := cmd.Run()
	if ctx.Err() == context.DeadlineExceeded {
		return 2, out.String(), errb.String(), opClassTimeout
	}
	if err != nil {
		var exitErr *exec.ExitError
		if !errors.As(err, &exitErr) {
			return 2, out.String(), errb.String(), opClassBadExit
		}
		rc = exitErr.ExitCode()
	}
	return rc, out.String(), errb.String(), ""
}

// extClass turns one run into an answer class. The live envelope kind wins
// over any prose guess, the same rule the 229-item table uses.
func extClass(rc int, stdout, stderr string) (class, reason string) {
	class, reason = classifyOpRun(rc, stdout, stderr)
	if class == opClassOK {
		// The ext envelope has the same three fields as the op envelope.
		var doc struct {
			Op     string          `json:"op"`
			Result json.RawMessage `json:"result"`
		}
		if err := json.Unmarshal([]byte(stdout), &doc); err != nil || doc.Op == "" || len(doc.Result) == 0 {
			return opClassBadJSON, reason
		}
	}
	return class, reason
}

// extRequireExit enforces the two legal exits: 0 with one JSON envelope, or 2
// with a reason on stderr and at most that one envelope on stdout.
func extRequireExit(t *testing.T, name string, rc int, stdout, stderr, class, reason string) {
	t.Helper()
	switch rc {
	case 0:
		if class != opClassOK {
			t.Fatalf("%s exited 0 but stdout is not one JSON envelope: %s\nstdout:\n%s", name, class, stdout)
		}
	case 2:
		if stdout != "" {
			var doc struct {
				Op    string `json:"op"`
				Error string `json:"error"`
				Kind  string `json:"kind"`
			}
			if err := json.Unmarshal([]byte(stdout), &doc); err != nil || doc.Op == "" || doc.Error == "" || doc.Kind == "" {
				t.Fatalf("%s refused and wrote stdout that is not one refusal envelope:\n%s", name, stdout)
			}
		}
		if reason == "" {
			t.Fatalf("%s exited 2 with no reason on stderr", name)
		}
	default:
		t.Fatalf("%s exited %d; only 0 (answer) and 2 (refusal) are contract exits\nstderr:\n%s", name, rc, stderr)
	}
}

// extEnv is the child environment for one run: no LRECON_ input variable,
// state in the test's temp root, and adb pointed at a closed port so a phone
// on the developer's desk cannot decide a row.
func extEnv(stateDir string) []string {
	return opContractEnv(stateDir)
}

// TestExtTableContractNoArgs runs every item with no target. For needs=true
// this is the missing-target contract; for the rest it is the one pass that
// touches nothing external.
func TestExtTableContractNoArgs(t *testing.T) {
	requireTableCLI(t)
	items := readExtAddendum(t)
	root := t.TempDir()
	timeout := opContractTimeout()
	observed := map[string]string{}
	for _, it := range items {
		o := extOps[it.Name]
		t.Run(it.Name, func(t *testing.T) {
			dir := filepath.Join(root, "cwd", it.Name)
			state := filepath.Join(root, "state", it.Name)
			for _, d := range []string{dir, state} {
				if err := os.MkdirAll(d, 0o755); err != nil {
					t.Fatal(err)
				}
			}
			rc, stdout, stderr, forced := runExtContract(extRunSpec{
				Binary:  cliPath,
				Name:    it.Name,
				Dir:     dir,
				Env:     extEnv(state),
				Timeout: timeout,
			})
			class, reason := extClass(rc, stdout, stderr)
			if forced != "" {
				class = forced
			}
			if opClassIsDefect(class) {
				t.Fatalf("%s with no target: %s (exit %d)\nstderr:\n%s", it.Name, class, rc, stderr)
			}
			extRequireExit(t, it.Name, rc, stdout, stderr, class, reason)
			if o.needs {
				if class != opClassNeedsArg {
					t.Fatalf("%s: needs=true must refuse for a missing target, got %s: %s", it.Name, class, reason)
				}
				if !strings.Contains(strings.ToLower(reason), "target path") {
					t.Fatalf("%s: refusal does not name the missing target: %s", it.Name, reason)
				}
			}
			if !extClassAccepted(it.NoArgs, class) {
				t.Errorf("%s: no target answered %s, the addendum accepts %v: %s", it.Name, class, extAccepted[it.NoArgs], reason)
			}
			observed[it.Name] = class
		})
	}
	if *updateExtTable {
		writeExtTableUpdate(t, func(tbl *extTable) {
			for i := range tbl.Ops {
				// shortcut: Ghidra rows answer differently on machines with the
				// engine installed, so they stay pinned to the committed class.
				if tbl.Ops[i].Route == "G" {
					continue
				}
				if c, ok := observed[tbl.Ops[i].Name]; ok {
					tbl.Ops[i].Observed.NoArgs = c
				}
			}
		})
	}
	assertExtObserved(t, "no_args", observed)
}

// TestExtTableContractWithTarget is the argument pass: every item that wants
// a target gets the real Mach-O fixture and must either answer or refuse
// honestly.
func TestExtTableContractWithTarget(t *testing.T) {
	requireTableCLI(t)
	items := readExtAddendum(t)
	root := t.TempDir()
	timeout := opContractTimeout()
	observed := map[string]string{}
	for _, it := range items {
		if !it.Needs {
			continue
		}
		// -short makes the engine unreachable instead of skipping the row: the
		// item still has to refuse honestly, and a real Ghidra import takes
		// 27-35 s cold, which is why the machine's install stays opt-in.
		t.Run(it.Name, func(t *testing.T) {
			dir := filepath.Join(root, "cwd", it.Name)
			state := filepath.Join(root, "state", it.Name)
			env, observedNow := extEnv(state), true
			rowTimeout := timeout
			if testing.Short() && it.Route == "G" {
				env = opEnvRoute("G", "ghidra made unreachable in -short", state)
				observedNow = false
			}
			if !testing.Short() && it.Route == "G" {
				// A cold Mach-O import takes 27-35 s idle, 73 s here and over
				// 110 s under `go test ./...` load. Both budgets have to clear
				// that: the CLI's own LRECON_GHIDRA_TIMEOUT and the harness
				// that would otherwise kill the row first.
				rowTimeout = max(timeout, ghidraRowTimeout)
				env = append(env, "LRECON_GHIDRA_TIMEOUT="+(rowTimeout-10*time.Second).String())
			}
			for _, d := range []string{dir, state} {
				if err := os.MkdirAll(d, 0o755); err != nil {
					t.Fatal(err)
				}
			}
			fixtures, err := tableFixtures(t, root)
			if err != nil {
				t.Fatalf("build fixtures: %v", err)
			}
			name := it.Fixture
			if name == "" || name == "-" {
				name = "macho"
			}
			src, ok := fixtures[name]
			if !ok {
				t.Fatalf("%s: addendum asks for fixture %q, which the test does not build", it.Name, name)
			}
			target := filepath.Join(dir, "target.bin")
			body, err := os.ReadFile(src)
			if err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(target, body, 0o644); err != nil {
				t.Fatal(err)
			}
			rc, stdout, stderr, forced := runExtContract(extRunSpec{
				Binary:  cliPath,
				Name:    it.Name,
				Target:  target,
				Dir:     dir,
				Env:     env,
				Timeout: rowTimeout,
			})
			class, reason := extClass(rc, stdout, stderr)
			if forced != "" {
				class = forced
			}
			if opClassIsDefect(class) {
				t.Fatalf("%s on %s: %s (exit %d)\nstderr:\n%s", it.Name, name, class, rc, stderr)
			}
			extRequireExit(t, it.Name, rc, stdout, stderr, class, reason)
			if !extClassAccepted(it.WithTarget, class) {
				t.Errorf("%s: with target answered %s, the addendum accepts %v: %s", it.Name, class, extAccepted[it.WithTarget], reason)
			}
			if observedNow {
				observed[it.Name] = class
			}
		})
	}
	if *updateExtTable {
		writeExtTableUpdate(t, func(tbl *extTable) {
			for i := range tbl.Ops {
				// shortcut: engine-dependent Ghidra rows keep the committed class.
				if tbl.Ops[i].Route == "G" {
					continue
				}
				if c, ok := observed[tbl.Ops[i].Name]; ok {
					tbl.Ops[i].Observed.WithTarget = c
				}
			}
		})
	}
	assertExtObserved(t, "with_target", observed)
}

func loadExtTable(path string) (*extTable, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var tbl extTable
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&tbl); err != nil {
		return nil, err
	}
	return &tbl, nil
}

// writeExtTableUpdate writes the table back with the observed classes.
func writeExtTableUpdate(t *testing.T, mutate func(*extTable)) {
	t.Helper()
	tbl, err := loadExtTable(extTablePath)
	if err != nil {
		t.Fatalf("reload %s for -update: %v", extTablePath, err)
	}
	mutate(tbl)
	if tbl.Note == "" {
		tbl.Note = extTableNote
	}
	b, err := json.MarshalIndent(tbl, "", " ")
	if err != nil {
		t.Fatal(err)
	}
	b = append(b, 10)
	if err := os.WriteFile(extTablePath, b, 0o644); err != nil {
		t.Fatal(err)
	}
	t.Logf("updated %s (%d rows)", extTablePath, len(tbl.Ops))
}

// assertExtObserved holds the table's observed column to this run: it is the
// class the last -update-ext measured, so a row that ran again in the same
// environment must reproduce it. An external tool appearing or vanishing moves
// no_engine <-> anything, so no_engine on either side is a machine fact and
// never op drift; anything else means the op or the table changed.
func assertExtObserved(t *testing.T, phase string, observed map[string]string) {
	t.Helper()
	if *updateExtTable {
		return
	}
	tbl, err := loadExtTable(extTablePath)
	if err != nil {
		t.Fatalf("load %s: %v", extTablePath, err)
	}
	seen := 0
	for _, row := range tbl.Ops {
		class, ran := observed[row.Name]
		if !ran {
			continue
		}
		want := row.Observed.NoArgs
		if phase == "with_target" {
			want = row.Observed.WithTarget
		}
		if want == "" {
			t.Errorf("%s: %s has no observed class; rerun with -update-ext", row.Name, phase)
			continue
		}
		seen++
		// The observed column is one machine's answer. Whether an external tool
		// is installed changes the class in both phases (a no-args row that
		// answers ok here answers no_engine there), so no_engine on either side
		// is that machine fact, not drift. Rows that answered without a tool
		// still have to reproduce; the accepted-set check above covers the rest.
		if class == want || class == opClassNoEngine || want == opClassNoEngine {
			continue
		}
		t.Errorf("%s: %s observed %s, table recorded %s; rerun -update-ext if the machine changed", row.Name, phase, class, want)
	}
	if seen == 0 {
		t.Fatalf("%s: no row was checked against the observed column", phase)
	}
}

// TestExtTableContractToolSuccess proves an external tool cannot pass by being
// absent: with a fake tool on PATH one item per family must reach ok. Every
// other pass accepts a refusal class, so without this the table stays green on
// a machine with no tools at all.
func TestExtTableContractToolSuccess(t *testing.T) {
	requireTableCLI(t)
	rt2TestTools(t, map[string]string{
		"adb":  "#!/bin/sh\necho device\n",
		"jadx": "#!/bin/sh\necho 'jadx 1.5.0'\n",
		"lldb": "#!/bin/sh\necho '(lldb) diagnostics dumped'\n",
	})
	root := t.TempDir()
	target := filepath.Join(root, "target.bin")
	if err := os.WriteFile(target, []byte("MZ"), 0o644); err != nil {
		t.Fatal(err)
	}
	cases := []struct{ name, target string }{
		{"adb_get_state", ""},
		{"jadx_plugins", ""},
		{"lldb_diagnostics", target},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			dir := filepath.Join(root, "cwd", c.name)
			state := filepath.Join(root, "state", c.name)
			for _, d := range []string{dir, state} {
				if err := os.MkdirAll(d, 0o755); err != nil {
					t.Fatal(err)
				}
			}
			rc, stdout, stderr, forced := runExtContract(extRunSpec{
				Binary:  cliPath,
				Name:    c.name,
				Target:  c.target,
				Dir:     dir,
				Env:     extEnv(state),
				Timeout: opContractTimeout(),
			})
			class, reason := extClass(rc, stdout, stderr)
			if forced != "" {
				class = forced
			}
			extRequireExit(t, c.name, rc, stdout, stderr, class, reason)
			if class != opClassOK {
				t.Fatalf("%s with a fake tool on PATH answered %s, not %s: %s", c.name, class, opClassOK, reason)
			}
		})
	}
}

// TestExtToolError prefers the cause over the banner: real tools print an
// INFO line first, and reporting that line hides the reason the caller has to
// act on.
func TestExtToolError(t *testing.T) {
	dir := t.TempDir()
	fake := filepath.Join(dir, "jadx")
	script := "#!/bin/sh\necho INFO\necho 'error: real cause' >&2\nexit 1\n"
	if err := os.WriteFile(fake, []byte(script), 0o755); err != nil {
		t.Fatal(err)
	}
	_, _, err := extRun(context.Background(), "jadx", fake)
	if err == nil {
		t.Fatal("extRun returned nil for a non-zero exit")
	}
	msg := err.Error()
	if !strings.Contains(msg, "error: real cause") {
		t.Fatalf("message lost the cause: %q", msg)
	}
	if strings.Contains(msg, "INFO") {
		t.Fatalf("message reported the banner: %q", msg)
	}
}
