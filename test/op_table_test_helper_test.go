package main

// Helpers for the op-table contract test (op_table_contract_test.go). This is
// a test-only helper file: nothing here ships in the lrecon binary.
//
// This file deliberately does not import "testing": it is a plain package
// file, so it must not depend on the test framework. The test file calls
// these functions and owns every assertion.
//
// The table in testdata/ops.json is one row per registered op: its route, its
// `needs` flag and the class of answer the CLI is expected to give with no
// target and with a fixture target. Measuring is done by running the built
// binary (the same one cli_test.go builds in TestMain), never by calling the
// op's Go function directly: the point is the CLI contract, which is exactly
// the seam the old tests never crossed (report B2/B3).

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
	"time"
)

const (
	// opTablePath is relative to the package directory; tests run there.
	opTablePath = "testdata/ops.json"
	// opFixtureSrcDir holds the source the contract test cross-compiles into
	// real artifacts. Binaries are built into a temp dir, not committed.
	opFixtureSrcDir = "testdata/fixtures/tiny"
	// opTableNote is written into every regenerated table.
	opTableNote = "Op contract table: one row per registered op. Generated by `go test -run TableContract -update`; do not hand-edit. no_args is the class observed with no target; with_target is the class observed on expect.fixture, except gated rows (route G/Y), which keep their skipped_* gate class and are not rewritten."
)

// Answer classes. `ok` means exit 0 and one JSON envelope; the refusal
// classes all mean exit 2, empty stdout and a reason on stderr.
//
// Table classes (lrecon/testdata/ops.json) are a *production-time* vocabulary,
// NOT the runtime errorKind set (lrecon/errors.go, closed 9: needs_arg,
// bad_arg, out_of_scope, no_engine, timeout, usage, io, state_conflict,
// internal). Only those nine are ever emitted live; the other table classes
// name a gate the table test did not run through, and must never be produced
// by the CLI (no fake kind, no string sniffing in production code). The map
// tableClassLiveKind below is the documented, test-locked bridge:
//
//	table class     live kind when the gate is lifted        note
//	ok              - (exit 0, {"op","target","result"})     real answer
//	needs_arg       needs_arg                              target/env/job field missing
//	bad_arg         bad_arg                                value given and wrong
//	out_of_scope    out_of_scope                           never done by contract
//	no_engine       no_engine                              tool/device/session absent
//	timeout         timeout (+stage)                       deadline hit, G 50s / Y 60s
//	usage           usage                                  flags cannot be one document
//	io              io                                     target could not be read/written
//	state_conflict  state_conflict                         earlier op must open the state
//	internal        internal                               lrecon's own fault
//	wrong_kind      bad_arg                                hint only: target reached the op but is not the artifact kind it reads; CLI emits bad_arg (TestOpSkipRefuses pins the live shape)
//	skipped_ghidra  no_engine / timeout / ok               Ghidra opt-in gate; LIVE: analyzeHeadless absent -> no_engine, JVM killed/timeout -> timeout+stage, present -> ok
//	skipped_tool    no_engine / bad_arg                    Y opt-in gate; LIVE: external tool absent -> no_engine, bad invocation -> bad_arg
//	not_applicable  - (no pass exists)                     needs=false rows have no target pass in the table
//
// TestTableContractInventory + TestOpClassLiveKindMap pin this map against
// kindList (errors.go) and against the table rows: a new table class without
// a live mapping, a table class that IS a runtime kind but maps elsewhere, or
// a skipped/not_applicable class used on the wrong route/needs, fails the
// build, not the sim.
const (
	opClassOK            = "ok"             // exit 0, one {"op","target","result"} JSON document
	opClassNeedsArg      = "needs_arg"      // exit 2, the call is missing a target / env / job field
	opClassBadArg        = "bad_arg"        // exit 2, any other honest refusal
	opClassOutOfScope    = "out_of_scope"   // exit 2, the request is outside what lrecon does
	opClassNoEngine      = "no_engine"      // exit 2, the tool, device or session behind the op is absent
	opClassTimeout       = "timeout"        // exit 2, a step hit its deadline (envelope carries stage)
	opClassUsage         = "usage"          // exit 2, the flags cannot be one document
	opClassIO            = "io"             // exit 2, the target could not be read or written
	opClassStateConflict = "state_conflict" // exit 2, the op needs an earlier op to open the state
	opClassInternal      = "internal"       // exit 2, lrecon's own fault; the message is the clue
	opClassWrongKind     = "wrong_kind"     // exit 2, the target is not the artifact kind this op reads [hint, not a runtime kind]
	opClassBadJSON       = "bad_json"       // exit 0 but stdout is not one op envelope: always a defect
	opClassPanic         = "panic"          // the process panicked: always a defect
	opClassBadExit       = "bad_exit"       // exit other than 0/2: always a defect

	opClassSkippedGhidra = "skipped_ghidra" // route G not run: opt-in, see LRECON_OPS_GHIDRA
	opClassSkippedTool   = "skipped_tool"   // route Y not run: opt-in, see LRECON_OPS_TOOLS
	opClassNotApplicable = "not_applicable" // needs=false, so there is no target pass
)

// opClassDefects are the observations that are never acceptable, whatever the
// table says: a panic, a hang, a malformed envelope or an unexpected exit code.
func opClassIsDefect(class string) bool {
	switch class {
	case opClassBadJSON, opClassPanic, opClassTimeout, opClassBadExit:
		return true
	}
	return false
}

// tableClassLiveKind is the table-class -> live-kind bridge documented above
// the const block. Values are closed-set errorKind strings, or "ok" for a
// real answer, or "" for no-pass rows. Every live value must be in kindList
// (errors.go); no table class may map to a value outside it.
var tableClassLiveKind = map[string]string{
	opClassOK:            "ok",
	opClassNeedsArg:      "needs_arg",
	opClassBadArg:        "bad_arg",
	opClassOutOfScope:    "out_of_scope",
	opClassNoEngine:      "no_engine",
	opClassTimeout:       "timeout",
	opClassUsage:         "usage",
	opClassIO:            "io",
	opClassStateConflict: "state_conflict",
	opClassInternal:      "internal",
	opClassWrongKind:     "bad_arg", // hint only: classifier still emits bad_arg live
	opClassSkippedGhidra: "no_engine",
	opClassSkippedTool:   "no_engine",
	opClassNotApplicable: "",
}

func opClassKnown(class string) bool {
	switch class {
	case opClassOK, opClassNeedsArg, opClassNoEngine, opClassWrongKind, opClassBadArg,
		opClassOutOfScope, opClassStateConflict, opClassTimeout, opClassUsage,
		opClassIO, opClassInternal,
		opClassSkippedGhidra, opClassSkippedTool, opClassNotApplicable:
		return true
	}
	return false
}

// opTable mirrors testdata/ops.json. Rows are sorted by name so the file is a
// stable record and a drift diff names the op that moved.
type opTable struct {
	Note string       `json:"note"`
	Ops  []opTableRow `json:"ops"`
}

type opTableRow struct {
	Name   string        `json:"name"`
	Route  string        `json:"route"`
	Needs  bool          `json:"needs"`
	Expect opExpectation `json:"expect"`
}

type opExpectation struct {
	NoArgs     string `json:"no_args"`
	WithTarget string `json:"with_target"`
	Fixture    string `json:"fixture,omitempty"`
	// Requires records what a needs_arg refusal must name (an LRECON_ env var
	// or a job field), so the refusal stays actionable instead of merely 2.
	Requires string `json:"requires,omitempty"`
}

func loadOpTable(path string) (*opTable, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var tbl opTable
	dec := json.NewDecoder(bytes.NewReader(b))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&tbl); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return &tbl, nil
}

// saveOpTable writes the table pretty-printed like the committed contract file.
// One-row-per-line compact output turned a content change into a 229+/2272-
// format diff, so the writer matches the committed format; json.MarshalIndent
// and a trailing newline keep git diff reviewable row by row via field changes.
func saveOpTable(path string, tbl *opTable) error {
	if tbl.Note == "" {
		tbl.Note = opTableNote
	}
	sortOpTableRows(tbl.Ops)
	b, err := json.MarshalIndent(tbl, "", "  ")
	if err != nil {
		return err
	}
	b = append(b, 10)
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, b, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

func sortOpTableRows(rows []opTableRow) {
	for i := 1; i < len(rows); i++ {
		for j := i; j > 0 && rows[j].Name < rows[j-1].Name; j-- {
			rows[j], rows[j-1] = rows[j-1], rows[j]
		}
	}
}

var (
	opANSI    = regexp.MustCompile(`\x1b\[[0-9;]*[A-Za-z]`)
	opNeedsRe = regexp.MustCompile(`lrecon_[a-z_]+ (is )?(not set|empty)`)
)

// opStderrMessage returns the one line of stderr a reader should see. Some ops
// paint progress with \r or ANSI writes, so the raw first line can be a
// half-erased fragment; split on both and keep the first clean lrecon: line.
func opStderrMessage(stderr string) string {
	clean := opANSI.ReplaceAllString(stderr, "")
	var first string
	for _, line := range strings.FieldsFunc(clean, func(r rune) bool { return r == '\n' || r == '\r' }) {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		if strings.HasPrefix(line, "lrecon:") {
			return line
		}
		if first == "" {
			first = line
		}
	}
	return first
}

// classifyOpRun turns one CLI run into an answer class plus the stderr reason.
// It mirrors the honesty rules of refuse(): exit 0 is a JSON envelope, exit 2
// is a refusal with an empty stdout, and a panicking or hanging process is a
// defect regardless of the table.
func classifyOpRun(rc int, stdout, stderr string) (class, reason string) {
	reason = opStderrMessage(stderr)
	if strings.Contains(stderr, "panic: ") || strings.Contains(stderr, "\ngoroutine ") ||
		strings.HasPrefix(stderr, "goroutine ") {
		return opClassPanic, reason
	}
	switch {
	case rc == 0:
		var doc struct {
			Op     string          `json:"op"`
			Result json.RawMessage `json:"result"`
		}
		if err := json.Unmarshal([]byte(stdout), &doc); err != nil || doc.Op == "" || len(doc.Result) == 0 {
			return opClassBadJSON, reason
		}
		// `"result": null`, a bare scalar or a string still fills RawMessage,
		// so the envelope check above passes it. TestOpMapResultExit0 promises
		// an object (`result map[string]any`): anything else is not an answer.
		var obj map[string]any
		if err := json.Unmarshal(doc.Result, &obj); err != nil || obj == nil {
			return opClassBadJSON, reason
		}
		return opClassOK, reason
	case rc != 2:
		return opClassBadExit, reason
	}
	// Ground truth: the live envelope kind. When the binary emitted a
	// refusal envelope, its kind wins over any prose guess. This is how
	// wrong_kind never leaks live (hint only; CLI emits bad_arg), how
	// collect_adb_bugreport needs_arg is not re-read as bad_arg, and how
	// out_of_scope is not re-read as bad_arg. skip classes
	// (skipped_ghidra/skipped_tool/not_applicable) are never produced
	// by a live run, so they never reach this branch.
	var env struct {
		Kind  string `json:"kind"`
		Error string `json:"error"`
	}
	if err := json.Unmarshal([]byte(stdout), &env); err == nil && env.Kind != "" {
		return env.Kind, env.Error
	}
	// No envelope on stdout (old binary / text mode): fall back to prose
	// classification. Prose is only a backstop, never the source when
	// an envelope kind exists.
	low := strings.ToLower(reason)
	low = strings.ReplaceAll(low, "needs an target path", "needs target path")
	low = strings.ReplaceAll(low, "needs a target path", "needs target path")
	switch {
	case strings.Contains(low, "needs target path"), opNeedsRe.MatchString(low),
		strings.Contains(low, "needs -"), strings.Contains(low, "job needs"), strings.Contains(low, "set lrecon_"):
		return opClassNeedsArg, reason
	case strings.Contains(low, "out of scope"), strings.Contains(low, "out-of-scope"):
		return opClassOutOfScope, reason
	case strings.Contains(low, "no session yet"):
		return opClassStateConflict, reason
	case strings.Contains(low, "not installed"), strings.Contains(low, "no device"),
		strings.Contains(low, "no session"), strings.Contains(low, "not found: install"),
		strings.Contains(low, "not on path"), strings.Contains(low, "decoder table"),
		strings.Contains(low, "failed to connect"), strings.Contains(low, "connection refused"),
		strings.Contains(low, "find service"), strings.Contains(low, "not ready"):
		return opClassNoEngine, reason
	case strings.Contains(low, " is not "), strings.Contains(low, "not a pe image"),
		strings.Contains(low, " has no "), strings.Contains(low, "cannot "),
		strings.Contains(low, "does not "), strings.Contains(low, "unexpected"),
		strings.Contains(low, "not an "), strings.Contains(low, "not a zip"),
		strings.Contains(low, "is too "):
		return opClassWrongKind, reason
	}
	return opClassBadArg, reason
}

// opGateLiveClass is what a gated row may answer when its engine is absent:
// the missing engine (no_engine), input it needs before the tool (needs_arg),
// the tool's own success (ok), an input-shape refusal checked before the gate
// (bad_arg, held to opRefusalNamesInput) or the op's bylaws (out_of_scope).
// A timeout, panic, bad envelope or bad exit is never allowed: those are
// defects the gate must not hide.
func opGateLiveClass(_ opTableRow, class string) bool {
	switch class {
	case opClassNoEngine, opClassNeedsArg, opClassOK, opClassBadArg, opClassOutOfScope:
		return true
	}
	return false
}

// opEnvelopeOp is the op name a success envelope reports, or "" when stdout is
// not one envelope. The contract test uses it to hold the answer to the row it
// asked for: a wrong-but-valid envelope must not satisfy a row.
func opEnvelopeOp(stdout string) string {
	var doc struct {
		Op string `json:"op"`
	}
	if err := json.Unmarshal([]byte(stdout), &doc); err != nil {
		return ""
	}
	return doc.Op
}

// opGateClass is the gate vocabulary a gated row publishes in the table.
func opGateClass(row opTableRow) string {
	if row.Route == "G" {
		return opClassSkippedGhidra
	}
	return opClassSkippedTool
}

// opRefusalNamesInput holds a bad_arg refusal to the input it was handed: the
// target's basename, or the word target/file/argument. "cannot open target"
// alone is not enough: the reader must learn which argument was wrong.
func opRefusalNamesInput(reason, target string) bool {
	low := strings.ToLower(reason)
	if base := strings.ToLower(filepath.Base(target)); base != "" && base != "." && strings.Contains(low, base) {
		return true
	}
	for _, word := range []string{"target", "file", "argument"} {
		if strings.Contains(low, word) {
			return true
		}
	}
	return false
}

// opRunSpec is one contract run of the built CLI.
type opRunSpec struct {
	Binary  string
	Name    string
	Target  string // empty: the no-target pass
	Dir     string // working directory, a temp dir so relative writes land there
	Env     []string
	Timeout time.Duration
}

// runOpContract executes `lrecon --op NAME [TARGET]` and reports its exit
// code. A timeout is reported as the timeout class, not as an error, so the
// test can name the op and its budget instead of dying on exec.
func runOpContract(spec opRunSpec) (rc int, stdout, stderr, class string) {
	args := []string{"--op", spec.Name}
	if spec.Target != "" {
		args = append(args, spec.Target)
	}
	ctx, cancel := context.WithTimeout(context.Background(), spec.Timeout)
	defer cancel()
	cmd := exec.CommandContext(ctx, spec.Binary, args...)
	cmd.Dir = spec.Dir
	cmd.Env = spec.Env
	var out, errb bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errb
	err := cmd.Run()
	if ctx.Err() == context.DeadlineExceeded {
		return 2, out.String(), errb.String(), opClassTimeout
	}
	if err != nil {
		var exitErr *exec.ExitError
		if !errors.As(err, &exitErr) {
			return 2, out.String(), errb.String(), opClassBadExit
		}
		rc = exitErr.ExitCode()
	}
	return rc, out.String(), errb.String(), ""
}

// opContractEnv is the child environment for one run: the developer's shell
// must not decide which branch an op takes, so every LRECON_ input variable is
// dropped and state is redirected into the test's temp root. HOME stays real
// because Ghidra discovery and tool lookups read it.
func opContractEnv(stateDir string) []string {
	drop := map[string]bool{
		"LRECON_STATE": true, "LRECON_AT": true, "LRECON_NAME": true,
		"LRECON_ARGS": true, "LRECON_QUERY": true, "LRECON_PATTERN": true,
		"LRECON_DECODERS": true, "LRECON_JOB": true,
	}
	env := make([]string, 0, len(os.Environ())+1)
	for _, kv := range os.Environ() {
		key, _, _ := strings.Cut(kv, "=")
		if drop[key] {
			continue
		}
		env = append(env, kv)
	}
	// A phone on the developer's desk must not decide the row either: point adb
	// at a closed port so the device ops take their "no device" branch and the
	// table records the CI class, not today's emulator state.
	return append(env, "LRECON_STATE="+stateDir, "ADB_SERVER_SOCKET=tcp:127.0.0.1:1")
}

// opFixtureSpec is one cross-compiled target. Files are named after the format
// so a failing row says "macho" and not a temp path.
type opFixtureSpec struct {
	Name   string
	GOOS   string
	GOARCH string
	Ext    string
}

var opFixtureSpecs = []opFixtureSpec{
	{"macho", "darwin", "arm64", ""},
	{"elf", "linux", "amd64", ""},
	{"pe", "windows", "amd64", ".exe"},
	{"wasm", "js", "wasm", ".wasm"},
}

// buildOpFixtures cross-compiles the tiny fixture program into real Mach-O,
// ELF, PE and wasm artifacts under dst. Committing four multi-megabyte
// binaries would bloat the repo and go stale; a Go toolchain is already a test
// prerequisite.
func buildOpFixtures(dst string) (map[string]string, error) {
	out := make(map[string]string, len(opFixtureSpecs))
	for _, spec := range opFixtureSpecs {
		path := filepath.Join(dst, spec.Name+spec.Ext)
		cmd := exec.Command("go", "build", "-trimpath", "-ldflags", "-s -w", "-o", path, ".")
		cmd.Dir = opFixtureSrcDir
		cmd.Env = append(os.Environ(),
			"CGO_ENABLED=0",
			"GOOS="+spec.GOOS,
			"GOARCH="+spec.GOARCH,
			"GOFLAGS=",
			"GOWORK=off",
		)
		var log bytes.Buffer
		cmd.Stdout, cmd.Stderr = &log, &log
		if err := cmd.Run(); err != nil {
			return nil, fmt.Errorf("build %s fixture (%s/%s): %v\n%s", spec.Name, spec.GOOS, spec.GOARCH, err, log.String())
		}
		out[spec.Name] = path
	}
	return out, nil
}

// opRequiresRes extracts the missing input named by a needs_arg refusal, in the
// three shapes the CLI uses today: an unset environment variable, an
// instruction to set one, and the job-field list of set_bookmark/record_unknown
// and friends.
var opRequiresRes = []*regexp.Regexp{
	regexp.MustCompile(`(LRECON_[A-Z_]+) (?:is )?(?:not set|empty)`),
	regexp.MustCompile(`set (LRECON_[A-Z_]+)`),
	regexp.MustCompile(`job needs (.*)`),
}

// opRequiresFrom records what a needs_arg refusal asked for, so the target pass
// can hold the message to the published requirement: a refusal that stops
// naming its input is a contract regression even if the class is unchanged.
func opRequiresFrom(class, reason string) string {
	if class != opClassNeedsArg {
		return ""
	}
	for _, re := range opRequiresRes {
		if m := re.FindStringSubmatch(reason); m != nil {
			return strings.TrimSpace(m[1])
		}
	}
	return ""
}
