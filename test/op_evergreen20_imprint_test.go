package main

// Imprinting drift: the verdict a tool reports for one file must not depend on
// which file it looked at first. lrecon has no multi-file mode (two targets is
// an error: "loop instead"), so both orders are run as separate CLI invocations
// and as in-process Probe calls, and every structured field is compared per
// file. Prose, timings and line counts are never compared.

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"strings"
	"testing"
	"time"
)

// imprintSample is fixed, sorted by path, and spans four shapes: a tiny file, a
// syscall-heavy file, a test file, a large main package, plus two fixtures from
// the corpus tree. Real .go files only, no generated bytes.
var imprintSample = []string{
	"../env/sim300/run/20261031-132631/w/202-ghdeep-3/gosrc-app/main.go",
	"main.go",
	"ops.go",
	"proc_unix.go",
	"cli_test.go",
	"skipped.go",
	"proctable.go",
}

// imprintVerdict is the machine-readable structure the tool claims per file.
type imprintVerdict struct {
	Exit   int
	Kind   string
	Plan   string
	Format string
	Size   int64
	Sha    string
}

func (v imprintVerdict) String() string {
	return fmt.Sprintf("exit=%d kind=%q plan=%q format=%q size=%d sha=%s",
		v.Exit, v.Kind, v.Plan, v.Format, v.Size, v.Sha)
}

type imprintJSON struct {
	Kind     string `json:"kind"`
	Plan     string `json:"plan"`
	Format   string `json:"format"`
	FileSize int64  `json:"file_size"`
	Target   struct {
		Size       int64  `json:"size"`
		FileSHA256 string `json:"file_sha256"`
	} `json:"target"`
}

func imprintCLI(t *testing.T, path string) imprintVerdict {
	t.Helper()
	if buildErr != nil {
		t.Fatalf("cli build failed: %v\n%s", buildErr, buildLog)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, cliPath, path, "--json")
	out, err := cmd.Output()
	v := imprintVerdict{Exit: 0}
	if err != nil {
		ee, ok := err.(*exec.ExitError)
		if !ok {
			t.Fatalf("%s: %v", path, err)
		}
		v.Exit = ee.ExitCode()
	}
	var j imprintJSON
	if uerr := json.Unmarshal(out, &j); uerr != nil {
		t.Fatalf("%s: --json produced no parseable envelope: %v\n%s", path, uerr, out)
	}
	v.Kind, v.Plan, v.Format = j.Kind, j.Plan, j.Format
	v.Sha = j.Target.FileSHA256
	v.Size = j.Target.Size
	if v.Size == 0 {
		v.Size = j.FileSize
	}
	return v
}

func imprintProbe(t *testing.T, path string) string {
	t.Helper()
	d, err := Probe(path)
	if err != nil {
		t.Fatalf("%s: Probe: %v", path, err)
	}
	b, err := json.Marshal(d)
	if err != nil {
		t.Fatalf("%s: marshal digest: %v", path, err)
	}
	return string(b)
}

func TestEvergreen20ImprintingDrift(t *testing.T) {
	// Order A: lightest first. Order B: heaviest first. Same files, same
	// invocations, only the leading file changes.
	asc := make([]string, len(imprintSample))
	copy(asc, imprintSample)
	type sized struct {
		path string
		size int64
	}
	stats := make([]sized, 0, len(asc))
	for _, p := range asc {
		st, err := os.Stat(p)
		if err != nil {
			t.Fatalf("sample file %s is missing: %v", p, err)
		}
		stats = append(stats, sized{p, st.Size()})
	}
	// Deterministic ordering: sort by size, ties broken by path.
	for i := 1; i < len(stats); i++ {
		for j := i; j > 0; j-- {
			if stats[j].size < stats[j-1].size ||
				(stats[j].size == stats[j-1].size && stats[j].path < stats[j-1].path) {
				stats[j], stats[j-1] = stats[j-1], stats[j]
				continue
			}
			break
		}
	}
	orderAsc := make([]string, len(stats))
	orderDesc := make([]string, len(stats))
	for i, s := range stats {
		orderAsc[i] = s.path
		orderDesc[len(stats)-1-i] = s.path
	}

	// Shape guard: the sample is only meaningful if the leading file of each
	// order really is a different shape. Tiny vs heavy must be far apart, and
	// the declared shapes must still exist.
	smallest, heaviest := stats[0], stats[len(stats)-1]
	if heaviest.size < 8*smallest.size {
		t.Fatalf("sample is too uniform to test imprinting: smallest %s=%d, heaviest %s=%d",
			smallest.path, smallest.size, heaviest.path, heaviest.size)
	}
	if smallest.size > 512 {
		t.Fatalf("smallest sample %s is %d bytes, expected a tiny file", smallest.path, smallest.size)
	}
	sysBody, err := os.ReadFile("proc_unix.go")
	if err != nil {
		t.Fatalf("read proc_unix.go: %v", err)
	}
	if !strings.Contains(string(sysBody), "syscall.") {
		t.Fatal("proc_unix.go no longer contains syscall calls: the syscall-heavy shape is gone")
	}
	hasTest, hasMainPkg := false, false
	for _, p := range imprintSample {
		if strings.HasSuffix(p, "_test.go") {
			hasTest = true
		}
		body, rerr := os.ReadFile(p)
		if rerr != nil {
			t.Fatalf("read %s: %v", p, rerr)
		}
		if strings.HasPrefix(string(body), "package main") {
			hasMainPkg = true
		}
	}
	if !hasTest || !hasMainPkg {
		t.Fatalf("sample lost its shapes: test file=%v main package=%v", hasTest, hasMainPkg)
	}

	// Pass 1 and 2 through the CLI, opposite orders.
	cliA := map[string]imprintVerdict{}
	cliB := map[string]imprintVerdict{}
	for _, p := range orderAsc {
		cliA[p] = imprintCLI(t, p)
	}
	for _, p := range orderDesc {
		cliB[p] = imprintCLI(t, p)
	}

	// Passes through the library in one process: this is where a package-level
	// mode imprinted by the first target would leak. Three orders, so a
	// monotonic imprint that makes pass A equal pass B still shows in pass C.
	probeA := map[string]string{}
	probeB := map[string]string{}
	probeC := map[string]string{}
	for _, p := range orderAsc {
		probeA[p] = imprintProbe(t, p)
	}
	for _, p := range orderDesc {
		probeB[p] = imprintProbe(t, p)
	}
	for i := len(imprintSample) - 1; i >= 0; i-- {
		probeC[imprintSample[i]] = imprintProbe(t, imprintSample[i])
	}

	// Sensitivity check on the comparison itself: a mutated verdict must not
	// compare equal, so a silent drift cannot pass through.
	probe := cliA[imprintSample[0]]
	mutated := probe
	mutated.Kind += "-imprinted"
	if probe == mutated {
		t.Fatal("verdict comparison is vacuous: a mutated kind still compares equal")
	}
	if probeA[imprintSample[0]] == imprintProbeMutated(t, imprintSample[0]) {
		t.Fatal("digest comparison is vacuous: a mutated digest still compares equal")
	}

	// Distinct files must still report distinct identities, otherwise the
	// per-file comparison is comparing one constant.
	seen := map[string]string{}
	for _, p := range imprintSample {
		v := cliA[p]
		if v.Sha == "" {
			t.Fatalf("%s: no file_sha256 in the envelope: %s", p, v)
		}
		if other, dup := seen[v.Sha]; dup {
			t.Fatalf("%s and %s report the same digest: sample files are not distinct", p, other)
		}
		seen[v.Sha] = p
	}

	for _, p := range imprintSample {
		a, b := cliA[p], cliB[p]
		if a != b {
			t.Fatalf("imprinting drift in CLI verdict for %s: order A (smallest first, position %d) %v vs order B (heaviest first, position %d) %v",
				p, imprintPos(orderAsc, p), a, imprintPos(orderDesc, p), b)
		}
		if probeA[p] != probeB[p] {
			t.Fatalf("imprinting drift in Probe digest for %s: order A (position %d) %s vs order B (position %d) %s",
				p, imprintPos(orderAsc, p), probeA[p], imprintPos(orderDesc, p), probeB[p])
		}
		if probeC[p] != probeA[p] {
			t.Fatalf("imprinting drift in Probe digest for %s: path order %s vs size order %s",
				p, probeC[p], probeA[p])
		}
		// A fresh process per file is the independent truth: an imprint in this
		// process cannot reach it, so a leaked mode shows up as a mismatch.
		if got := imprintVerdictOf(t, probeA[p]); got != a {
			t.Fatalf("%s: in-process Probe verdict %v disagrees with fresh-process CLI verdict %v (imprinted mode)",
				p, got, a)
		}
		if a.Exit != 0 {
			t.Fatalf("%s: tool exited %d on a readable .go file, expected 0", p, a.Exit)
		}
	}

	// The leading file of order B must be the heaviest, and its verdict must
	// match the one it got as the last file of order A.
	if orderDesc[0] != heaviest.path || orderAsc[len(orderAsc)-1] != heaviest.path {
		t.Fatalf("orders do not bracket the heaviest file: %v vs %v", orderAsc, orderDesc)
	}
	t.Logf("no drift across %d files: probes=%d cli=%d", len(imprintSample), len(probeA), len(cliA))
}

func imprintPos(order []string, p string) int {
	for i, s := range order {
		if s == p {
			return i + 1
		}
	}
	return -1
}

// imprintVerdictOf reads the structured fields out of a marshaled Digest, so an
// in-process digest can be compared field by field with a CLI envelope.
func imprintVerdictOf(t *testing.T, digest string) imprintVerdict {
	t.Helper()
	var j imprintJSON
	if err := json.Unmarshal([]byte(digest), &j); err != nil {
		t.Fatalf("digest is not parseable: %v", err)
	}
	v := imprintVerdict{Kind: j.Kind, Plan: j.Plan, Format: j.Format, Sha: j.Target.FileSHA256, Size: j.Target.Size}
	if v.Size == 0 {
		v.Size = j.FileSize
	}
	return v
}

// imprintProbeMutated re-probes the file and returns the digest with one field
// changed, proving the string comparison used above can see a difference.
func imprintProbeMutated(t *testing.T, path string) string {
	t.Helper()
	d, err := Probe(path)
	if err != nil {
		t.Fatalf("%s: Probe: %v", path, err)
	}
	d.Kind += "-imprinted"
	b, err := json.Marshal(d)
	if err != nil {
		t.Fatalf("%s: marshal mutated digest: %v", path, err)
	}
	return string(b)
}
